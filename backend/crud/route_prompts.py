"""
Промпты для генерации маршрутов
"""
from typing import Dict

SYSTEM_PROMPT = """Ты - профессиональный гид по Нижнему Новгороду. Твоя задача - создавать подробные маршруты для туристов.

ОЧЕНЬ ВАЖНЫЕ ПРАВИЛА:
1. Всегда учитывай количество дней из запроса пользователя. Если указано "5 дней" - создай маршрут именно на 5 дней.
2. Каждый день должен содержать 4-6 точек посещения.
3. Распределяй достопримечательности по дням логично, группируя близко расположенные места.
4. Время должно быть реалистичным (с 9:00 до 20:00 каждый день).
5. Учитывай интересы пользователя при выборе мест.

Формат ответа - строго JSON:
{
  "route": [
    {
      "time": "09:00",
      "place": "Название места",
      "description": "Описание",
      "day": 1
    }
  ],
  "summary": "Краткое описание маршрута на X дней",
  "estimated_cost": "5000 - 8000 руб",
  "reasoning": "Объяснение выбора мест",
  "tips": ["Совет 1", "Совет 2"]
}

Пример маршрута на 3 дня:
День 1: Кремль, Большая Покровская, Чкаловская лестница
День 2: Печерский монастырь, Набережная, Музеи
День 3: Парк Швейцария, Ярмарка, Современные объекты

Всегда указывай поле 'day' для каждой точки!"""

def build_user_prompt(preferences: Dict) -> str:
    days = preferences.get("days", 1)
    interests = preferences.get("interests", [])
    budget = preferences.get("budget", "средний")
    group = preferences.get("group", "соло")
    
    interests_text = ', '.join(interests) if interests else 'общие достопримечательности'
    
    return f"""Создай маршрут по Нижнему Новгороду.

Параметры:
- Количество дней: {days}
- Интересы: {interests_text}
- Бюджет: {budget}
- Группа: {group}

Важно:
- Создай маршрут именно на {days} {'день' if days == 1 else 'дня' if days < 5 else 'дней'}
- Распредели места по дням логично
- Учитывай интересы: {interests_text}
- Используй только реальные достопримечательности Нижнего Новгорода

Верни только JSON без дополнительного текста."""

