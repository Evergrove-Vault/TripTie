def generate_route_with_llm(
    city_name: str,
    interests: List[str],
    days: int,
    budget_level: str = "средний",
    group: str = "соло"
) -> Dict[str, Any]:
    """
    Генерирует маршрут для Нижнего Новгорода
    Просто распределяет места по дням
    """
    # Проверяем, что это Нижний Новгород
    city_lower = city_name.lower()
    nnov_variants = [
        "нижний новгород", "н.новгород", "ннов", "нижний",
        "н.новг", "нижнем новгороде", "нижнем", "nnovgorod", "nizhny novgorod"
    ]
    
    is_nnovgorod = any(variant in city_lower for variant in nnov_variants)
    
    if not is_nnovgorod:
        return {
            "route": [],
            "summary": f"Генерация маршрута для {city_name} пока не поддерживается",
            "estimated_cost": "Не указано",
            "reasoning": "Сервис работает только для Нижнего Новгорода",
            "tips": [f"Для города {city_name} маршрут будет добавлен позже"]
        }
    
    # Ограничиваем количество дней
    days = max(1, min(days, 7))
    
    # Берем места по дням (4 места на день)
    places_per_day = 4
    total_places_needed = days * places_per_day
    
    # Берем нужное количество мест из списка
    selected_places = NOVGOROD_PLACES[:total_places_needed]
    
    # Распределяем по дням
    route = []
    for day in range(1, days + 1):
        day_start_idx = (day - 1) * places_per_day
        day_end_idx = day_start_idx + places_per_day
        day_places = selected_places[day_start_idx:day_end_idx]
        
        for i, place in enumerate(day_places):
            coords = get_coordinates(place["name"])
            
            route.append({
                "id": f"day{day}_point{i+1}",
                "time": place["time"],
                "place": place["name"],
                "description": place["description"],
                "day": day,
                "order": i + 1,
                "coordinates": coords
            })
    
    # Вычисляем стоимость
    base_cost = 2000 if budget_level == "низкий" else 5000 if budget_level == "средний" else 10000
    total_cost = base_cost * days
    
    return {
        "route": route,
        "summary": f"Маршрут по Нижнему Новгороду на {days} {'день' if days == 1 else 'дня' if days < 5 else 'дней'}",
        "estimated_cost": f"{total_cost} - {total_cost + 2000} руб на человека",
        "reasoning": f"Выбраны основные достопримечательности Нижнего Новгорода, распределенные по {days} дням",
        "tips": [
            "Удобная обувь обязательна - город холмистый",
            "Попробуйте нижегородские пряники",
            f"Распределите {days} дней так: день 1 - центр и кремль, день 2 - история, день 3 - культура",
            "Используйте общественный транспорт для перемещения между районами",
            "Не забудьте посетить смотровые площадки с видом на Волгу"
        ],
        "map_config": {
            "center": CENTER_COORDS,
            "zoom": 13,
            "bounds": {
                "north": 56.3500,
                "south": 56.2300,
                "east": 44.0500,
                "west": 43.7800
            }
        }
    }
